def checklist_for(event):
    """특수 상황 1건에 맞는 {"before","after","sources"}. 체크리스트가 없는 종류는 None."""
    if event.event_type == 'WARNING':
        base = CHECKLISTS.get((event.detail or {}).get('warning_type'), GENERIC)
        sources = [SRC_KMA, SRC_RDA]
    elif event.event_type == 'PEST_INCREASE':
        base = PEST_CHECKLIST
        sources = [SRC_RDA]
    else:
        return None
    return {'before': base['before'], 'after': base['after'], 'sources': sources}
