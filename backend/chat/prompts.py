def josa(word, with_final, without_final):
    """받침에 맞는 조사를 붙인다: josa('사과', '을', '를') → '사과를'. 한글이 아니면 둘 다 적는다."""
    last = word[-1] if word else ''
    if not ('가' <= last <= '힣'):
        return f'{word}{with_final}({without_final})'
    final = (ord(last) - 0xAC00) % 28
    if with_final == '으로':  # ㄹ 받침은 "로" (예: 귤로)
        return word + ('로' if final in (0, 8) else '으로')
    return word + (with_final if final else without_final)

